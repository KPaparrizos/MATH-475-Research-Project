/*
    This file classifies near miss families from the
    exhastive check performed by uc_conj_verify.c up 
    to isomorphism. The program computes a canonical 
    representation for each family by applying all relabelings
    of [m] to the family and keeping the smallest one, then
    sorting canonical representations and grouping isomorphic ones. 
    For each near-miss family the program reports various statistics
    and whether it is one of the three known slack-1 families. Output 
    is written to CSV files.
    
*/

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

// Represents a family on [m], where m <= 6. Same representation scheme as uc_conj_verify.c
typedef uint64_t small_t; 

// Returns number of members in a family
static int popc_small(small_t x)
{
    return __builtin_popcountll(x);
}

// Comparison function used by qsort, returns -1 if *a < *b, 0 if *a = *b, and 1 if *a > *b
static int cmp_u64(const void *a, const void *b)
{
    uint64_t x = *(const uint64_t *)a, y = *(const uint64_t *)b;
    return x < y ? -1 : x > y;
}

// Number of permutations performed
static int nperm;
// Double array whose entry [q][A] represent the image of the subset A after performing
// the qth permutation generated by build_perms
static unsigned char perm_set[720][64];

// Builds perm_set table
static void build_perms(int mm)
{
    // Represents current permutation, e.g. (0, 1, 2, 3, 4, 5)
    int p[6];

    // Sets identity permutation
    for (int i = 0; i < mm; i++)
    {
        p[i] = i; 
    }

    // Number of permutations recorded
    nperm = 0;

    // Traverses and records all permutations, once per each loop
    for (;;)
    {
        // Records what happens to each subset under the permutation in perm_set
        for (int A = 0; A < (1 << mm); A++)
        {
            // New subset being built
            int B = 0;

            // Traverses permutation
            for (int i = 0; i < mm; i++)
            {
                // Checks if element i is in A. If so, puts p[i] in B
                if ((A >> i) & 1)
                {
                    B |= 1 << p[i];
                }
            }

            // Stores B, the subset A after performing the permutation
            perm_set[nperm][A] = (unsigned char)B;
        }

        // Adds current permutation to count
        nperm++;

        int i = mm - 2;

        // Finds which position in permutation to change in lexicographic order
        while (i >= 0 && p[i] > p[i + 1])
        {
            i--;
        }

        // Stop if at last permutation and exit loop
        if (i < 0)
        {
            break;
        }

        int j = mm - 1;

        // Finds new value to swap into position in permutation
        while (p[j] < p[i])
        {
            j--;
        }

        // Performs swap on permutation
        int t = p[i];
        p[i] = p[j];
        p[j] = t;

        // Reverses tail to obtain new permutation
        for (int a = i + 1, b = mm - 1; a < b; a++, b--)
        {
            t = p[a];
            p[a] = p[b];
            p[b] = t;
        }
    }
}

// Given a family, returns its canonical representation
static small_t canonical(small_t G, int mm)
{
    // Begin with smallest possitlbe
    small_t best = ~(small_t)0;

    // Checks all permutations
    for (int q = 0; q < nperm; q++)
    {
        // Represents canonical form
        small_t c = 0;

        // Loops over all subsets
        for (int A = 0; A < (1 << mm); A++)
        {
            // If a subset is a member, look up its image in perm_set and adds to
            // canonical representation
            if ((G >> A) & 1)
            {
                c |= (small_t)1 << perm_set[q][A];
            }
        }

        // Keep smallest relabeling, which is canonical representation
        if (c < best)
        {
            best = c;
        }
    }

    // Return canonical representation
    return best;
}

// Counts how many members of a given family contain a given element
static int freq_small(small_t F, int mm, int i)
{
    int f = 0;

    // Traverses all subsets
    for (int A = 0; A < (1 << mm); A++)
    {
        // Checks if the family contains a subset and the subset contains in the element.
        // If so, increases count.
        if (((F >> A) & 1) && ((A >> i) & 1))
        {
            f++;
        }
    }

    return f;
}

// Given a family, computes slack
static int slack_small(small_t F, int mm)
{
    // Frequency of most frequent element
    int top = 0;

    // Traverses all elements
    for (int i = 0; i < mm; i++)
    {
        // Gets frequency of each element
        int f = freq_small(F, mm, i);

        // Stores most frequent element
        if (f > top)
        {
            top = f;
        }
    }

    // Computes slack of element
    return 2 * top - popc_small(F);
}

// Checks whether a family splits as a product
static int is_product(small_t F, int mm)
{
    // Representation of universe as an integer
    int U = (1 << mm) - 1, N = popc_small(F);

    // Tests all subsets other than the empty set and the universe
    for (int X = 1; X < U; X++)
    {
        // Possible families the given family could be a product of
        small_t Gx = 0, Hy = 0;

        // Traverses all subsets
        for (int A = 0; A <= U; A++)
        {
            // Checks if the family contains a subset. If so, adds the intersection of 
            // the subset and X to G and the intersection of the subset and U \ X to H
            if ((F >> A) & 1)
            {
                Gx |= (small_t)1 << (A & X);
                Hy |= (small_t)1 << (A & ~X & U);
            }
        }

        // Returns 1 if the product agrees with the original family
        if (popc_small(Gx) * popc_small(Hy) == N)
        {
            return 1;
        }
    }

    // Return 0 otherwise
    return 0;
}

// Builds and returns 3 slack-1 families
static void named_families(int mm, small_t out[3])
{
    // Universe
    int U = (1 << mm) - 1;
    // Singleton subset
    int b = 1 << (mm - 1);     
    // Universe with a and b removed   
    int Bset = (U >> 1) & ~1;   
    // Initialize 3 slack-1 families in output array  
    out[0] = out[1] = out[2] = 0;

    // Traverses all subsets
    for (int A = 0; A <= U; A++)  
    {
        // Adds all subsets to the output family except for the singleton
        if (A != b)
        {
            out[0] |= (small_t)1 << A;
        }
    }

    // Traverses all subsets of [m - 1]
    for (int A = 0; A < b; A++)   /* (B) all subsets of {0, ..., mm-2}, plus [m] */
    {
        // Adds all subsets to the output family 
        out[1] |= (small_t)1 << A;
    }

    // Adds the set [m]
    out[1] |= (small_t)1 << U;

    // Traverses all subsets
    for (int S = 0; S <= U; S++)  /* (C) every S in P(B), and S + a + b */
    {
        // If a set is contained in the Bset add it to the family and adds the union of the set 
        // with {a, b} to the family
        if ((S & ~Bset) == 0)
        {
            out[2] |= ((small_t)1 << S) | ((small_t)1 << (S | 1 | b));
        }
    }

    // Adds the set B union A to the family
    out[2] |= (small_t)1 << (Bset | 1); /* (C) the set B + a */
}

// Compares classes and orders them for qsort
static int cmp_class(const void *a, const void *b)
{ 
    const uint64_t *x = a, *y = b;

    // Compare rows (slack, N, canonical representation, copies) one at a time
    // and return smaller based on rows
    for (int k = 0; k < 3; k++)
    {
        if (x[k] != y[k])
        {
            return x[k] < y[k] ? -1 : 1;
        }
    }

    return 0;
}

// Prints/writes members of a family to a file
static void print_members(FILE *o, small_t F, int mm)
{
    int first = 1;

    for (int A = 0; A < (1 << mm); A++)
    {
        if ((F >> A) & 1)
        {
            fputs(first ? "{" : ";{", o);
            first = 0;
            int fe = 1;

            for (int i = 0; i < mm; i++)
            {
                if ((A >> i) & 1)
                {
                    fprintf(o, fe ? "%d" : ",%d", i);
                    fe = 0;
                }
            }

            fputs("}", o);
        }
    }
}
// Given a list of near-miss families, groups them into isomorphism classes, describes 
// each class, and checks if they fit with the 3 described slack-1 classes 
static int classify(small_t *G, size_t n, int mm, const char *prefix)
{
    // Build permutation table
    build_perms(mm);
    small_t named[3] = {0, 0, 0}, named_c[3] = {0, 0, 0};

    // Build 3 known slack-1 families
    if (mm >= 3)
    {
        named_families(mm, named);

        for (int k = 0; k < 3; k++)
        {
            named_c[k] = canonical(named[k], mm);
        }
    }

    
    uint64_t *key = malloc((n ? n : 1) * 8);

    // Replace all families with canonical representations
    for (size_t i = 0; i < n; i++)
    {
        key[i] = canonical(G[i], mm);
    }

    // Sort list of canonical representations
    qsort(key, n, 8, cmp_u64);

    uint64_t *rows = malloc((n ? n : 1) * 32);
    size_t nc = 0;

    // Groups canonical representations into isomorphism classes and stores slack,
    // N, canonical representation, and number of copies
    for (size_t i = 0; i < n;)
    {
        size_t j = i;

        while (j < n && key[j] == key[i])
        {
            j++;
        }

        small_t F = key[i];
        rows[4 * nc] = slack_small(F, mm);
        rows[4 * nc + 1] = popc_small(F);
        rows[4 * nc + 2] = F;
        rows[4 * nc + 3] = j - i;
        nc++;
        i = j;
    }

    // Sort classes
    qsort(rows, nc, 32, cmp_class);

    FILE *o = NULL;

    // Creates output CSV file
    if (prefix)
    {
        char path[512];
        snprintf(path, sizeof path, "%s_classes.csv", prefix);
        o = fopen(path, "w");

        if (!o)
        {
            perror(path);
            return 1;
        }

        fputs("m,class,slack,N,labeled_copies,freqs_sorted,has_singleton,product,named,members,bitmask\n", o);
        printf("writing %s\n", path);
    }

    printf("\nnear-miss classes for m = %d (%zu labeled families -> %zu isomorphism classes)\n", mm, n, nc);
    int per_slack[3] = {0}, per_named[3] = {0}, per_prod[3] = {0}, found[3] = {0};

    // Traverses all classes, computing information and writing to the CSV
    for (size_t c = 0; c < nc; c++)
    {
        // Reads a class's stored rpw
        small_t F = rows[4 * c + 2];
        int slack = (int)rows[4 * c], N = (int)rows[4 * c + 1];
        int f[6];

        // Gets frequencies of each element
        for (int x = 0; x < mm; x++)
        {
            f[x] = freq_small(F, mm, x);
        }

        // Sorts frequencies of elements by descending order
        for (int a = 0; a < mm; a++) 
        {
            for (int b2 = a + 1; b2 < mm; b2++)
            {
                if (f[b2] > f[a])
                {
                    int t = f[a];
                    f[a] = f[b2];
                    f[b2] = t;
                }
            }
        }

        int sing = 0;

        // If the family contains a singleton, set sing to 1. Otherwise 
        // leave sing as 0.
        for (int x = 0; x < mm; x++)
        {
            if ((F >> (1 << x)) & 1)
            {
                sing = 1;
            }
        }

        // Determines if the class is a product.
        int prod = is_product(F, mm);
        const char *nm = "";

        // Checks the three known slack-1 families to determine if 
        // the class is one of these families
        for (int k = 0; k < 3 && mm >= 3; k++)
        {
            if (F == named_c[k])
            {
                nm = k == 0 ? "A" : k == 1 ? "B" : "C";
                found[k] = 1;
            }
        }

        // Update summary counts
        if (slack >= 0 && slack <= 2)
        {
            per_slack[slack]++;
            per_named[slack] += nm[0] != 0;
            per_prod[slack] += prod;
        }

        // Writes information to CSV
        if (o)
        {
            fprintf(o, "%d,%zu,%d,%d,%llu,\"", mm, c + 1, slack, N, (unsigned long long)rows[4 * c + 3]);

            for (int x = 0; x < mm; x++)
            {
                fprintf(o, x ? ";%d" : "%d", f[x]);
            }

            fprintf(o, "\",%d,%d,%s,\"", sing, prod, nm);
            print_members(o, F, mm);
            fprintf(o, "\",0x%016llx\n", (unsigned long long)F);
        }
    }

    // Print information for log
    for (int s = 1; s <= 2; s++)
    {
        printf("  slack %d: %d classes (%d are the named families A/B/C, %d split as products)\n",
               s, per_slack[s], per_named[s], per_prod[s]);
    }

    // Print information for log
    if (mm >= 3)
    {
        printf("  named families present: (A) %s, (B) %s, (C) %s\n",
               found[0] ? "yes" : "NO", found[1] ? "yes" : "NO", found[2] ? "yes" : "NO");
        printf("  prediction 'the slack-1 classes are exactly A, B, C': %s\n",
               (per_slack[1] == per_named[1] && found[0] && found[1] && found[2]) ? "HOLDS" : "FAILS");
    }

    // Close CSV
    if (o)
    {
        fclose(o);
    }

    free(rows);
    free(key);
    return 0;
}

// Tests program for correctness
static int selftest(void)
{
    int ok = 1;
    int fact = 1;

    // Checks if buildperms produces all labelings
    for (int mm = 1; mm <= 6; mm++)
    {
        fact *= mm;
        build_perms(mm);
        printf("m = %d: %d relabelings (expected %d) %s\n", mm, nperm, fact, nperm == fact ? "ok" : "WRONG");
        ok &= nperm == fact;
    }

    // Checks if 3 known near-miss families are built correctly
    for (int mm = 3; mm <= 6; mm++)
    {
        small_t nf[3];
        named_families(mm, nf);
        int sizes[3] = {(1 << mm) - 1, (1 << (mm - 1)) + 1, (1 << (mm - 1)) + 1};

        for (int k = 0; k < 3; k++)
        {
            int good = popc_small(nf[k]) == sizes[k] && slack_small(nf[k], mm) == 1;
            printf("m = %d: family (%c) has N = %d, slack %d %s\n", mm, "ABC"[k],
                   popc_small(nf[k]), slack_small(nf[k], mm), good ? "ok" : "WRONG");
            ok &= good;
        }
    }

    printf(ok ? "self-tests passed\n" : "SELF-TESTS FAILED\n");
    return !ok;
}

// Splits CSV line into fields
static int split_csv(char *line, char **fields, int maxf)
{
    int n = 0;
    char *p = line;

    while (*p && n < maxf)
    {
        if (*p == '"')
        {
            p++;
            fields[n++] = p;

            while (*p && *p != '"')
            {
                p++;
            }

            if (*p)
            {
                *p++ = 0;
            }

            if (*p == ',')
            {
                p++;
            }
        }
        else
        {
            fields[n++] = p;

            while (*p && *p != ',' && *p != '\n' && *p != '\r')
            {
                p++;
            }

            if (*p)
            {
                *p++ = 0;
            }
        }
    }

    return n;
}

// Runs full program
int main(int argc, char **argv)
{
    const char *infile = NULL, *prefix = NULL;
    int want_m = 6, maxslack = 2;

    // Reads command-line arguments
    for (int a = 1; a < argc; a++)
    {
        if (!strcmp(argv[a], "--selftest"))
        {
            return selftest();
        }
        else if (!strcmp(argv[a], "--m") && a + 1 < argc)
        {
            want_m = atoi(argv[++a]);
        }
        else if (!strcmp(argv[a], "--maxslack") && a + 1 < argc)
        {
            maxslack = atoi(argv[++a]);
        }
        else if (!strcmp(argv[a], "--csv") && a + 1 < argc)
        {
            prefix = argv[++a];
        }
        else if (argv[a][0] != '-' && !infile)
        {
            infile = argv[a];
        }
        else
        {
            fprintf(stderr, "unknown argument %s\n", argv[a]);
            return 1;
        }
    }

    if (!infile)
    {
        fprintf(stderr, "usage: ./uc_classify FAMILIES.csv [--m 6] [--maxslack 2] [--csv PREFIX]\n");
        return 1;
    }

    if (want_m < 1 || want_m > 6)
    {
        fprintf(stderr, "--m must be 1..6\n");
        return 1;
    }

    // Open CSV with all near-miss families
    FILE *in = fopen(infile, "r");

    if (!in)
    {
        perror(infile);
        return 1;
    }

    static char line[1 << 16];
    char *fld[64];

    // Check for empty file
    if (!fgets(line, sizeof line, in))
    {
        fprintf(stderr, "empty file\n");
        return 1;
    }

    // Split header into column names
    int nf = split_csv(line, fld, 64), c_m = -1, c_emp = -1, c_slack = -1, c_reason = -1, c_bits = -1;

    // Record position of each needed column
    for (int i = 0; i < nf; i++)
    {
        if (!strcmp(fld[i], "m"))
        {
            c_m = i;
        }
        else if (!strcmp(fld[i], "has_empty"))
        {
            c_emp = i;
        }
        else if (!strcmp(fld[i], "slack"))
        {
            c_slack = i;
        }
        else if (!strcmp(fld[i], "reason"))
        {
            c_reason = i;
        }
        else if (!strncmp(fld[i], "bitmask", 7))
        {
            c_bits = i;
        }
    }

    if (c_m < 0 || c_emp < 0 || c_slack < 0 || c_reason < 0 || c_bits < 0)
    {
        fprintf(stderr, "input must be a families CSV from uc_conj_verify --csv\n");
        return 1;
    }

    
    size_t cap = 1024, n = 0;
    small_t *G = malloc(cap * sizeof(small_t));

    // Keep near-misses with wanted m
    while (fgets(line, sizeof line, in))
    {
        if (split_csv(line, fld, 64) <= c_bits)
        {
            continue;
        }

        if (atoi(fld[c_m]) != want_m || atoi(fld[c_emp]) != 1)
        {
            continue;
        }

        if (strcmp(fld[c_reason], "near_miss") || atoi(fld[c_slack]) > maxslack)
        {
            continue;
        }

        if (n == cap)
        {
            cap *= 2;
            G = realloc(G, cap * sizeof(small_t));
        }

        G[n++] = strtoull(fld[c_bits], NULL, 16);
    }

    fclose(in);
    printf("read %zu near misses with m = %d and slack <= %d from %s\n", n, want_m, maxslack, infile);
    int rc = classify(G, n, want_m, prefix);
    free(G);
    return rc;
}
